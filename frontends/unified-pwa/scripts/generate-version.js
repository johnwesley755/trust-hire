import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const rootDir = path.resolve(__dirname, '..');
const pkgPath = path.resolve(rootDir, 'package.json');
const publicDir = path.resolve(rootDir, 'public');
const versionJsonPublicPath = path.resolve(publicDir, 'version.json');
const distDir = path.resolve(rootDir, 'dist');
const versionJsonDistPath = path.resolve(distDir, 'version.json');
const srcDir = path.resolve(rootDir, 'src');
const versionTsPath = path.resolve(srcDir, 'version.ts');

try {
  const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
  const version = pkg.version || '1.0.0';
  const buildTime = new Date().toISOString();

  const versionData = {
    version,
    buildTime,
  };

  // 1. Write public/version.json
  if (!fs.existsSync(publicDir)) {
    fs.mkdirSync(publicDir, { recursive: true });
  }
  const payload = JSON.stringify(versionData, null, 2) + '\n';
  fs.writeFileSync(versionJsonPublicPath, payload, 'utf-8');
  console.log(`[generate-version] Wrote public/version.json: version ${version}`);

  // 2. Write dist/version.json if dist exists
  if (fs.existsSync(distDir)) {
    fs.writeFileSync(versionJsonDistPath, payload, 'utf-8');
    console.log(`[generate-version] Wrote dist/version.json: version ${version}`);
  }

  // 3. Write src/version.ts
  const versionTsContent = `// Auto-generated by scripts/generate-version.js - DO NOT EDIT MANUALLY
export const APP_VERSION = '${version}';
export const APP_BUILD_TIME = '${buildTime}';
`;
  fs.writeFileSync(versionTsPath, versionTsContent, 'utf-8');
  console.log(`[generate-version] Wrote src/version.ts: version ${version}`);

} catch (error) {
  console.error('[generate-version] Failed to generate version files:', error);
  process.exit(1);
}
